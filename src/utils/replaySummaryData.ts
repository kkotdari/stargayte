// 리플레이 요약을 '문장'이 아니라 '무슨 일이 있었나'로 저장하기 위한 형식(요청).
//
// 예전에는 완성된 한국어 문장을 그대로 DB에 넣었다. 그러면 등록 순간의 닉네임과 그때의
// 문구가 영원히 굳는다 — 나중에 누가 닉네임을 바꾸거나(회원 정보 수정), 비회원으로 남아
// 있던 게임 아이디가 실제 회원으로 연결되거나, 전술 설명 문구를 더 낫게 고쳐도 이미 등록된
// 경기들은 옛말을 계속 보여준다.
//
// 그래서 저장하는 건 다음 세 가지뿐이다.
//   - 어떤 일이었나(k): 문장 틀의 키. 문구 자체는 replaySummaryText.ts에만 있다.
//   - 누가 했나(who): 리플레이 원본 게임 아이디. 회원 pk가 아니라 이 값을 쓰는 이유는,
//     이게 그 경기 시점의 유일한 증거이고(GameResultSlot.rawName 주석 참고) 회원 연결은 나중에
//     바뀔 수 있기 때문이다. 볼 때마다 지금의 연결로 다시 풀어 현재 닉네임을 보여준다.
//   - 무엇으로(p): 유닛/건물/테크는 screp 영문 키로, 수치는 숫자로. 한국어 표기가 바뀌어도
//     저장된 값은 그대로다.
//
// 이렇게 두면 문구를 고치는 건 코드 한 곳을 고치는 일이 되고, 이미 등록된 경기들도 다음
// 조회부터 새 문구·새 닉네임으로 읽힌다.

/** 저장 형식 버전. 틀 키의 의미를 바꿔야 할 때만 올린다(문구만 바꿀 땐 그대로).
 *
 *  1 → 2: 자리(pos)의 뜻이 달라졌다. 예전에는 '그 무렵 찍은 명령의 중심'이라 일꾼의 자원
 *  클릭과 건물의 랠리 클릭이 섞여 대부분 제 집 언저리를 가리켰는데, 이제는 명령마다 주인을
 *  짚어(replayParser의 orderPositions.by) 그 둘을 빼고 어택 지정만 골라 쓴다. 화살표는 이
 *  값을 목표로 삼으므로, 옛 값에 새 뜻을 씌우면 엉뚱한 곳(자기 기지)을 가리킨다(지적) —
 *  버전으로 갈라 옛 요약에는 이 값을 안 쓴다. 옛 경기는 제어판의 '경기 재분석'으로 올린다. */
export const REPLAY_SUMMARY_VERSION = 2;

export interface ReplaySummaryBeat {
  /** 문장 틀 키(replaySummaryText.ts의 TEMPLATES). 모르는 키는 조용히 건너뛴다. */
  k: string;
  /** 이 일을 한 쪽이 이겼나 — 같은 틀도 이긴 쪽/진 쪽의 맺음이 다르다. */
  won: boolean;
  /** 행위자들의 리플레이 원본 게임 아이디. */
  who: string[];
  /** 부차 행위자(팀에서 특히 활약한 사람 등). 없으면 생략. */
  who2?: string[];
  /** 당한 쪽 — "관우의 저글링 성큰을 뚫음"처럼 상대를 지목하는 문장에서만. */
  whom?: string[];
  /** 일어난 프레임 — 이야기를 시간순으로 늘어놓는 데만 쓴다. */
  at?: number | null;
  /** 틀에 꽂히는 값들. 유닛/건물/테크는 screp 영문 키, 나머지는 숫자/불리언. */
  p?: Record<string, string | number | boolean | string[] | number[]>;
  /** 원본 게임 아이디 → 그 무렵 그 사람이 병력을 보낸 자리(타일 좌표). 미니맵 스냅에
   *  아바타를 놓는 데 쓴다(요청). 근거는 이동·공격 명령 좌표뿐이라 '있던 곳'이 아니라
   *  '보낸 곳'이고, 명령이 몇 개 안 찍힌 사람은 아예 빠진다(replaySummary의 beatPositions).
   *  맵 좌표를 못 읽은 리플레이와 옛 데이터에는 없다. */
  pos?: Record<string, [number, number]>;
  /** 원본 게임 아이디 → 그 사람이 그 무렵 '헤집은 자리들'(타일 좌표, 시간순). 한 문장이
   *  여러 곳을 말할 때만 있다(지적: "사방을 찔렀으면 사방에 이모지가 있어야 할 듯") —
   *  pos가 그중 가장 붐빈 한 곳이라면 이쪽은 상대 본진 단위로 나눈 전부다. 그림은 자리마다
   *  화살표를 하나씩 긋고, 문장도 이 수를 보고 '사방'이라 부를지를 정한다.
   *  한 곳뿐인 이야기에는 없다(그건 pos가 이미 말한다). 옛 데이터에도 없다. */
  spots?: Record<string, [number, number][]>;
  /** 원본 게임 아이디 → 그 사람이 '무엇으로' 거기 갔나(screp 영문 유닛·건물 키). 미니맵이
   *  화살표 기둥 위에 이름표로 붙인다(요청: 모든 공격·포토러시·성큰러시·몰래 배럭·방어타워·
   *  옆탱 등에 다 적용). 건물을 박은 이야기는 그 건물, 병력을 몰고 간 이야기는 그 무렵 실제로
   *  명령을 받은 유닛이다. 옛 요약에는 없다. */
  units?: Record<string, string[]>;
  /** 원본 게임 아이디 → 그 무렵 그 사람이 굴린 병력의 크기(요청: 병력 규모에 따라 화살표
   *  두께도 다르게). 리플레이에 '지금 병력이 몇 기'는 없다 — 그 문장 시각 직전 몇 분 동안
   *  뽑은 전투 유닛 수로 대신한다(replaySummary의 arrowSizes). 급습 문장이 "질럿 13기"라고
   *  말할 때 쓰는 것과 같은 근거이고, 초반이 아니면 죽은 병력이 빠지지 않으므로 '그 무렵
   *  얼마나 뽑고 있었나'로 읽어야 한다. 옛 요약에는 없다. */
  sizes?: Record<string, number>;
  /** 그 무렵 오간 대사 — 미니맵이 말한 사람 옆에 말주머니로 띄운다(요청: 스냅으로 선정한
   *  부근의 채팅만). who는 원본 게임 아이디, at은 프레임. 이어 친 말은 한 줄로 묶여 있고,
   *  한 대사는 가장 가까운 스냅 하나에만 붙는다(replaySummary의 withChat).
   *  양쪽이 다 본 말(전체챗)만 담는다(요청: 팀챗 없애고 전체챗만) — 가르는 근거는
   *  replaySummary의 withChat 주석. 옛 요약에는 없다. */
  chat?: { who: string; text: string; at: number }[];
  /** 원본 게임 아이디 → 그 시각까지 그 사람이 갖춘 규모(병력 + 건물 몫). 미니맵이 아바타
   *  닉네임 밑에 다섯 칸 기세 눈금으로 그린다 — 한때 체력바였는데 "활성도에 가까운 값이라
   *  체력바로 읽히면 안 된다"는 지적으로 바꿨다(ReplayMinimap의 VigorPips 주석 참고).
   *  스냅에 안 나오는 사람도 아바타는 늘 떠 있으므로 전원 몫이 들어 있고, 시각이 없는
   *  문장에는 붙지 않는다. 리플레이에 죽음이 없어 '지금 살아 있는 병력'이 아니라 '여기까지
   *  쌓아 올린 것'이다 — 그래서 화면에서도 절대 수치로는 안 읽고, 같은 스냅의 1등을 100으로
   *  둔 비율로만 그린다(요청: 맵마다 자원 수급이 달라 판 밖의 잣대를 대면 안 된다.
   *  ReplayMinimap의 PowerBar 주석). 옛 요약에는 없다. */
  hp?: Record<string, number>;
}

export interface ReplaySummaryData {
  v: number;
  /** 리플레이가 승자를 못 가려낸 경기를 등록할 때 붙는다(요청: 검토창 없이 바로 등록하고
   *  활동 카드에서 빨간 글씨로 알리기) — result 필드 자체는 GameOutcome 중 하나(무승부로
   *  채운다)라야 해서, "진짜 판별이 아니라 임의로 채웠다"는 사실은 여기 따로 남긴다.
   *  옛 데이터에는 없다(=판별된 경기). */
  resultUncertain?: boolean;
  /** 일대일이었나 — 개인전에서는 "1팀이", "양 팀이" 같은 팀 용어를 쓰지 않는다(요청).
   *  옛 데이터에는 없어 생략 가능하고, 없으면 예전처럼 팀 용어를 쓴다. */
  duel?: boolean;
  /** 경기 전체 길이(프레임). '초반'은 절대 시간이 아니라 경기 길이에 대비해 봐야 한다(지적) —
   *  40분 경기의 8분과 9분 경기의 8분은 전혀 다른 자리다. 옛 데이터에는 없어 생략 가능하다. */
  end?: number;
  /** (옛 데이터 전용) 원본 게임 아이디 → 시작 지점을 시계로 부른 값(1~12). 한동안 요약
   *  문장에 "정구(1시)"처럼 붙였는데, 미니맵이 생기면서 걷어냈다(요청: 팀 언급과 몇시는
   *  빼도 되겠다) — 어디서 시작했는지는 이제 그림이 보여준다. 이미 저장된 경기에는 이 값이
   *  남아 있어 형식으로는 남겨 두지만, 읽는 곳은 없다. */
  spots?: Record<string, number>;
  /** 원본 게임 아이디 → 본진 자리(타일 좌표). 미니맵에 그 사람의 아바타+닉네임을 늘
   *  띄워 두는 자리다(요청). 옛 데이터에는 없어 생략 가능하다. */
  bases?: Record<string, [number, number]>;
  /** 원본 게임 아이디 → 그 사람 본진 살림의 한가운데(타일 좌표). bases가 '시작 지점에 선
   *  사람'의 자리라면 이쪽은 '실제로 건물을 편 자리'다 — 액션 이모지를 아바타에 겹치지
   *  않고 진짜 본진 위에 세우는 데 쓴다(요청: 본진 이모지는 아바타가 아니라 본진 건물
   *  자리에). 시작 지점 언저리의 건물만 세므로 멀티·센터 포토에는 끌려가지 않는다.
   *  옛 데이터에는 없어 생략 가능하고, 없으면 보는 쪽이 시작 지점을 그대로 쓴다. */
  hubs?: Record<string, [number, number]>;
  /** 원본 게임 아이디 → 옮겨 앉은 자리들([새 본진 x, y, 옮긴 프레임], 시간순). 주로 짓는
   *  자리가 바뀌면 이사한 것이다(요청) — 그 시점부터 옛 본진은 흑백으로 남기고 아바타를 새
   *  자리로 옮긴다. 쫓겨 다니면 여러 번 옮기므로 목록이다(요청). 옛 데이터에는 없다. */
  moves?: Record<string, [number, number, number][]>;
  /** 원본 게임 아이디 → 크게 망한 프레임. 건물·유닛 생산이 현저히 떨어져 끝까지 회복하지
   *  못한 지점(또는 실제 탈락 시점)이다(요청) — 그때부터 본진에 해골을 얹는다.
   *  옛 데이터에는 없어 생략 가능하다. */
  downs?: Record<string, number>;
  /** 그중 '완전히 끝난'(탈락) 시점만 — 해골은 이쪽에만 붙고, 생산이 무너진 빈사는
   *  회복 반창고(❤️‍🩹)로 간다(요청). 옛 요약에는 없어서 그때는 downs를 그대로 쓴다. */
  elims?: Record<string, number>;
  beats: ReplaySummaryBeat[];
}

/* ── 사건을 '같은 때'로 묶는 창 ────────────────────────────────────────────────
   요청: 타임 윈도우를 경기 전반에 똑같이 두지 말고 초반엔 자잘하게, 후반으로 갈수록 크게.

   실측(172판)이 그 필요를 확인해 줬는데, 이유는 예상과 달랐다. 한 교전이 이어진 길이는
   경기 내내 거의 그대로였다(중앙값 47초 → 55초). 달라지는 것은 '장면과 장면 사이'다 —
   같은 자리에서 다음 교전이 다시 벌어지기까지 걸린 시간의 하위 25%가

       0~5분 35초 · 5~10분 57초 · 10~15분 68초 · 15~20분 79초 · 20분 이후 86초

   였다. 즉 초반에는 40~90초짜리 고정 창이 '다음 장면'까지 삼키고(서로 다른 일이 한
   문장으로 묶인다), 후반에는 한 장면이 여러 문장으로 쪼개진다.

   그래서 배율은 위 수치를 그대로 따라간다(5~10분을 1로 놓은 비율 0.61 / 1.0 / 1.19 /
   1.39 / 1.51). 5분에 0.75, 10분에 1.1, 20분 이후 1.5로 완만하게 오르고 양끝을 묶는다.

   이 배율은 '이야기를 묶는 창'에만 쓴다. 교전 자체를 찾는 창(replayTactics의
   FIGHT_WINDOW_SEC, replaySummary의 CLASH_WINDOW_FRAMES, 리콜을 한 수로 묶는
   RECALL_SAME_SEC)은 위 실측대로 교전 길이가 시간대와 무관하므로 고정이고, 러시·패스트
   테크처럼 시각 자체가 정의인 문턱도 물론 고정이다. */
export function scenePace(sec: number): number {
  /* 후반에 창을 넓히는 쪽을 아예 없앴다(지적: 후반 전투가 너무 묶인다 — 두 번째). 상한을
     1.5 → 1.25로 낮췄는데도 같은 지적이 다시 나와서, 이번에는 상한을 1로 놓고 실제로
     무엇이 달라지는지를 172판 전체로 재 봤다: 상한 1.25와 1의 요약은 문장 1142개가
     한 글자도 다르지 않았다(0.85까지 내려도 한 문장 차이). 후반의 사건들은 애초에
     기준값(45~90초) 안에 들어오거나 몇 분씩 떨어져 있어서, 창을 그 사이에서 늘리고
     줄이는 것으로는 아무것도 안 붙고 안 떨어진다.
     그러니 이 상한은 이야기를 더 묶을 수만 있고 얻는 것은 없다 — 1로 못 박는다.
     초반을 좁히는 쪽(0.6)은 그대로 둔다: 그쪽은 실측대로 다음 장면이 30~40초 만에
     또 오는 구간이라 창을 좁혀야 서로 다른 일이 안 붙는다.
     후반 문장이 길어 보이는 진짜 까닭은 창이 아니라 한 문장이 부르는 이름 수였다 —
     replaySummary의 CLASH_NAME_SHARE·clashTech 주석에 실측을 남겼다. */
  return Math.min(1, Math.max(0.6, 0.55 + sec / (20 * 60)));
}

/** 그 프레임 무렵에 '같은 때'로 볼 창(초) — base는 중반(5~10분) 기준값이다.
 *  시각을 모르는 beat는 배율 없이 기준값 그대로 쓴다. */
export function sceneWindowSec(base: number, frame: number | null | undefined): number {
  if (typeof frame !== "number") return base;
  return base * scenePace(frame * SECONDS_PER_FRAME);
}

/** 1 프레임 = 0.042초(replayParser와 같은 상수). */
const SECONDS_PER_FRAME = 0.042;

/** 서버에서 받은 값이 우리가 아는 형식인지 — JSON 컬럼이라 무엇이든 들어올 수 있다. */
export function isReplaySummaryData(v: unknown): v is ReplaySummaryData {
  if (!v || typeof v !== "object") return false;
  const d = v as Partial<ReplaySummaryData>;
  return typeof d.v === "number" && Array.isArray(d.beats);
}
