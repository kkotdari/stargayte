/** 칭호 설명(요청: 버튼 부활 + 목록) — 이름과 "어떻게 받나"를 표(TITLES)에서 그때그때
 *  만든다. 절대평가라 조건이 곧 설명이다: 손으로 적어 두면 문턱을 고칠 때마다 두 곳이
 *  어긋나고, 이 화면은 그 어긋남이 바로 거짓말이 되는 자리다. */
export type EpithetRank = "전설" | "에픽" | "일반";

export interface EpithetGuideRow {
  label: string;
  how: string;
  rank: EpithetRank;
  /** 이긴 판만 세는 칭호인가 — 설명에 그 한마디를 덧붙인다. */
  wonOnly: boolean;
}

export function epithetGuideRows(): EpithetGuideRow[] {
  const pct = (v: number) => `${Math.round(v * 100)}%`;
  const rows = TITLES.map((t) => {
    const tier = t.tier ?? 2;
    const boost = TIER_BOOST[tier] ?? 1;
    const score = (t.weight ?? 0) * boost;
    const count = t.scale === "count";
    const share = t.minPlaysShare ?? 0;   // 칭호마다 제 값이다(COUNT_SHARE 삭제 주석)
    const where = t.race ? `${t.race} 판` : "제 판";
    // 마법 칭호의 근거는 문장으로 적혀 있다("게임에서 핵 사용") — 설명에서는 앞머리를 걷는다.
    const what = (t.why ?? "기록").replace(/^게임에서 /, "");
    /* 조건을 전부 적는다(요청: 몇 % 이상인지 다 명시) — 비율·최소 횟수·판수 문턱이 다
       걸려 있는데 일부만 적으면, 조건을 넘은 줄 알았던 사람이 왜 못 받았는지 알 길이 없다. */
    const bits: string[] = [];
    if (count) {
      if (share > 0) bits.push(`${what} ${where}의 ${pct(share)} 이상 (${where.replace("제 판", "판")} 5판부터)`);
      else bits.push(`${what}`);
      if ((t.min ?? 1) > 1) bits.push(`최소 ${t.min}${t.unit ?? "번"}`);
    } else {
      if (t.min !== undefined) {
        bits.push(`${what} ${t.min < 1 ? pct(t.min) : `${t.min}${t.unit ?? ""}`} 이상`);
      } else {
        bits.push(what);
      }
    }
    /* 등급은 구조로 가른다 — 전설은 승률 계열(sticky), 에픽은 3점 이상, 나머지가 일반.
       이름 짓는 규칙(표 머리)과 같은 선이다. */
    const rank: EpithetRank = t.sticky === true ? "전설" : score >= 3 ? "에픽" : "일반";
    return { label: t.label, how: bits.join(" · "), rank, wonOnly: t.won === true, score };
  });
  /* 이름이 사람마다 달라지는 두 줄({n})은 손으로 적는다 — 맵·종족 이름이 들어가야 말이
     되는데, 표에는 그 자리가 비어 있다. */
  return rows.map((r) => {
    if (r.label !== "{n}") return r;
    if (r.how.startsWith("그 맵 승수")) {
      return {
        ...r,
        label: "○○의 여왕 (맵 이름이 앞에 붙어요)",
        how: `그 맵에서 ${MAP_MIN_PLAYS}판 이상 · 승률 ${Math.round(MAP_MIN_RATE * 100)}% 이상`,
      };
    }
    return {
      ...r,
      label: "저그의 절대군주 · 프로토스의 수호자 · 테란의 전설",
      how: `그 종족으로 ${MIN_PLAYS_MODE}판 이상 · 제 판의 ${pct(RACE_MIN_SHARE)} 이상 · 승률 ${RACE_MIN_RATE}% 이상`,
    };
  }).sort((a, b) => (Number(b.rank === "전설") - Number(a.rank === "전설")) || (b.score - a.score))
    .map(({ label, how, rank, wonOnly }) => ({ label, how, rank, wonOnly }));
}

/** 회원 → 화면에 보일 칭호 하나(그 사람이 얻은 것 중 가장 높은 것).
 *
 *  절대평가다(요청) — 한때 거의 모든 칭호가 "클럽 최다/1위"라는 상대평가였는데, 그러면
 *  제일 많이 뛰는 한 사람이 표를 싹쓸이한다(실제로 그랬다: 한 사람이 열여섯 자격을 다
 *  가져갔다). 이제 칭호마다 절대 조건(제 판의 몇 %, 최소 몇 번, 수치 문턱)이 있고, 그걸
 *  넘은 사람은 누구든 그 칭호를 얻는다 — 같은 칭호를 여럿이 가질 수 있고, 한 사람이 여러
 *  칭호를 가질 수 있다(요청). 화면에는 그중 점수가 가장 높은 하나가 보인다(요청).
 *  '물려주기'도 함께 없어졌다 — 임자라는 개념 자체가 없다. */
/** 클럽에서 열린 내전 전체 판수 — 참여 퀸의 분모다(요청: 전체 경기수에 맞춰 나간다).
 *  epithetsOf를 부르기 전에 부르는 쪽이 채워 준다(useEpithets). 모듈 변수인 이유는 Title.value의
 *  시그니처(s, of)에 끼워 넣을 자리가 없어서다 — 계산 한 번에 한 값이라 이걸로 충분하다. */
let clubTotalGames: number | null = null;

export function epithetsOf(
  pool: EpithetSubject[],
  ctx?: { totalGames?: number | null },
): Map<string, Epithet> {
  clubTotalGames = ctx?.totalGames ?? null;
  const out = new Map<string, Epithet>();
  const ranked = pool.filter((p) => p.stats.plays >= MIN_PLAYS);

  /** 자격 하나 — 이 사람이 이 칭호의 조건을 넘었다. */
  interface Claim {
    title: Title;
    id: string;
    label: string;
    raw: number;
    /** 그 사람의 여러 자격 중 무엇을 보일지 고르는 점수 — 사람 사이를 견주는 값이 아니다. */
    score: number;
    order: number;
    /** 등급(전설 0 · 에픽 1 · 일반 2) — 대표를 고를 때 점수보다 먼저다. */
    rank: number;
    /** 동점대 — 무게가 비슷한 칭호들의 묶음(클수록 위). 같은 등급 안의 1차 기준이다. */
    band: number;
    /** 성취도 — 조건을 얼마나 크게 넘겼나. 같은 동점대 안의 2차 기준이다(요청). */
    reach: number;
    /** 이 값을 잰 판수 — 종족 칭호면 그 종족 판수다. 문턱(minPlaysShare)이 쓰는 분모다. */
    denom: number;
    /** 같은 자리의 이긴 판수 — 근거 문장의 '승리게임 몇 %'가 쓴다(winsOf 주석). */
    wonDenom: number;
  }
  const claims: Claim[] = [];
  TITLES.forEach((title, order) => {
    /* (삭제) 급별 최소 판수(MIN_PLAYS_TIER)·수치 칭호 최소 판수(MIN_PLAYS_RATE) — 걷었다
       (요청: 앞으로를 생각해서 판수 문턱이 아니라 수치로 거른다). 판이 쌓일수록 판수 문턱은
       뜻을 잃고, 우연을 거르는 몫은 이미 수치 조건(비율·최소 횟수·절대 문턱)이 맡고 있다.
       승률·종족·맵·팔색조처럼 표본이 조건의 일부인 칭호만 제 판수 조건을 값 안에 갖는다. */
    for (const p of ranked) {
      const v = title.value(p.stats, p);
      if (v === null || !(v > 0)) continue;
      const tier = title.tier ?? 2;
      /* 판수 대비 문턱 — 그 사람 판(종족 칭호면 그 종족 판)의 몇 할에서는 나왔어야 한다.
         칭호가 따로 정해 두지 않았으면 급에 맞는 기본값이 걸린다(COUNT_SHARE). */
      // 비율은 칭호마다 제 값이다(위 COUNT_SHARE 삭제 주석) — 안 적혔으면 비율 조건이 없다.
      const share = title.minPlaysShare ?? 0;
      if (share > 0) {
        // 분모는 전체 판수이되, vsWins가 선 칭호만 승리 판수다(Title.vsWins 주석).
        const denomPlays = title.vsWins ? winsOf(title, p) : denomOf(title, p);
        /* 표본 다섯 판은 있어야 비율이 말이 된다(지적: 옆탱 2번으로 퀸이 됐다 — 테란 판이
           몇 판뿐이면 두 번이 곧 100%다). 승률의 8판과 같은 결의 표본 조건이지, 걷어낸
           일괄 판수 문턱과는 다르다 — 분모가 서야 비율 조건 자체가 성립한다. */
        if (denomPlays < 5) continue;
        if (v < Math.ceil(denomPlays * share)) continue;
        /* 카운트 하한 — 비율과 별개다(위 countMinFor 주석). 클럽 전체 판수에 비례하고,
           그 칭호가 얼마나 흔한 수인가(= 제 비율 문턱)에도 비례한다. */
        if (v < countMinFor(share)) continue;
      }
      // 절대 문턱 — 이 값을 넘으면 받는다. 남이 얼마나 했는지는 안 본다(요청: 절대평가).
      if (title.min !== undefined && v < title.min) continue;
      const label = title.name
        ? title.label.replace("{n}", title.name(p.stats, p) ?? "")
        : title.label;
      if (!label || label.includes("{n}")) continue;
      /* 대표를 고르는 세 겹(요청: 비슷비슷한 것들은 동점대로 묶고 횟수·퍼센트가 높은 걸
         우선) —
         ① 등급(전설 › 에픽 › 일반): 점수만으로 고르면 횟수 칭호가 등급을 무시하고 이긴다.
         ② 동점대(band): 같은 등급 안에서 비슷한 칭호끼리 한 묶음으로 본다(요청) — 묶음은
            갈래(KIND_RANK) 넷이다: 한방 › 승률 › 명예 › 경기력. 크게 우열이 없는 것끼리는
            한 칸에 둔다(지적) — 같은 칸 안의 무게 차이는 "무엇이 더 그 사람다운가"를 말하지
            못하고, 오히려 성취도를 덮는다.
         ③ 성취도(reach): 같은 묶음 안에서는 그 조건을 얼마나 크게 넘겼나로 가른다 — 횟수
            칭호는 판 대비 비율(raw/denom), 수치 칭호는 문턱 대비 배수(v/min)다. 열두 판 중
            여덟 번(67%) 한 수가 무게 반 점 높은 세 번(25%)짜리보다 그 사람을 잘 말한다. */
      const boost = TIER_BOOST[tier] ?? 1;
      const grade = title.sticky ? 0 : (title.weight ?? 0) * boost >= 3 ? 1 : 2;
      const denomPlays = denomOf(title, p);
      const reach = title.scale === "count"
        ? (denomPlays > 0 ? v / denomPlays : v)
        : (title.min ? v / title.min : 1);
      claims.push({
        title, id: p.id, label, raw: v, denom: denomPlays, wonDenom: winsOf(title, p),
        /* 동점대 — 칭호의 갈래 그대로다(요청: 비슷한 칭호끼리 묶고 그 안에서는 얼마나
           강하게 만족했나로 가른다). 한때 점수에서 뽑았는데(반올림(점수÷3)) 그건 갈래를
           점수로 흉내 낸 것이라, 실제로는 54개 중 43개가 한 칸에 쏟아졌다 — 전술(4)과
           유닛(1.5)이 같은 칸이고, 정작 비슷한 손 수치(3)와 명예(6)는 다른 칸이었다.
           이름으로 묶으면 칸이 뜻대로 서고, 점수는 성취도 뒤의 잔가지로 물러난다. */
        band: KIND_RANK[title.kind ?? "경기력"],
        reach, score: (title.weight ?? 0) * (title.scale === "count" ? v : reach) * boost, order,
        rank: grade,
      });
    }
  });

  /* 보일 것을 고르는 차례 — 등급 › 동점대 › 성취도(요청) › 점수 › 표 차례. */
  claims.sort((a, b) =>
    (a.rank - b.rank)
    || (b.band - a.band) || (b.reach - a.reach)
    || (b.score - a.score) || (a.order - b.order) || a.id.localeCompare(b.id));
  /* 근거를 함께 남긴다(지적: "왜 이 칭호가 나오지?") — 화면은 이 문장을 툴팁·글자로 보여
     준다. "클럽 최다/1위" 꼬리는 걷었다(요청: 절대평가) — 이제 남과 견준 값이 아니라
     그 문장이 곧 조건 충족의 증거다. */
  const whyOf = (c: Claim): string => {
    /* 1 이하만 비율이다 — 한때 "10 미만의 소수는 전부 %"로 적어서 판당 5.6채가 "559%채",
       종족 3.02개가 "302%개"로 나갔다(지적 스크린샷). 채·기·개 같은 수는 소수 한 자리로
       적는다. */
    const shown = c.raw <= 1
      ? `${Math.round(c.raw * 100)}%`
      : c.raw >= 10 || Number.isInteger(c.raw)
        ? `${Math.round(c.raw)}`
        : `${Math.round(c.raw * 10) / 10}`;
    /* 근거는 "무엇을 몇 판에서 했나 (어느 무리의 몇 %인가)"다(요청) —
         뮤탈 견제 2판 (저그 승리게임 50%)
       분모가 무리마다 다르다: 이긴 판만 세는 수(전술·마법)는 그 종족의 이긴 판이 무리이고,
       져도 세는 수(GG·이사)는 전체 판이 무리다. 세는 자리와 견주는 자리가 같아야 "50%"가
       무슨 말인지 읽힌다 — 한때 이긴 판 수를 전체 판수로 나눠 적어서(4번 — 저그 28판 중
       14%), 28판이 저그 전체인지 이긴 판인지부터 안 잡혔다.
       문턱은 그대로 전체 판수로 잰다(winsOf 주석) — 근거는 뜻을 알리는 자리이고 문턱은
       맞춰 온 잣대다.
       마법 칭호(perUse)는 한 판에 여러 번 나올 수 있어 판수로 못 부른다 — "핵 사용 3번"으로
       적고, 견준 무리는 판수 그대로 밝힌다. */
    const what = (c.title.why ?? "기록").replace(/^게임에서 /, "");
    const countable = c.title.scale === "count" && c.title.unit === "번";
    if (countable) {
      // 이긴 판만 세는 수는 이긴 판이 무리, 아니면 전체 판이 무리다.
      const pool = c.title.won ? c.wonDenom : c.denom;
      const poolName = `${c.title.race ? `${c.title.race} ` : ""}${c.title.won ? "승리게임" : "전체 게임"}`;
      const n = Math.round(c.raw);
      if (c.title.perUse) {
        return `${what} ${n}번 (${poolName} ${pool}판)`;
      }
      return pool > 0 && c.raw <= pool
        ? `${what} ${n}판 (${poolName} ${Math.round((c.raw / pool) * 100)}%)`
        : `${what} ${n}판`;
    }
    return `${c.title.won ? "이긴 판에서 " : ""}${what} ${shown}${c.title.unit ?? ""}`;
  };
  // 한 사람의 첫 자격(가장 높은 것)이 화면에 보이는 칭호다 — 나머지 자격도 그 사람 것이지만
  // (요청: 여러 개 보유), 표의 자리는 한 줄이라 대표 하나만 나간다.
  for (const c of claims) {
    if (out.has(c.id)) continue;
    out.set(c.id, { label: c.label, why: whyOf(c) });
  }
  /* 자격 전부 갈무리(칭호 시뮬레이션·프로필이 읽는다) — 절대평가라 이 목록이 곧 "그 사람이
     보유한 칭호 전부"다. */
  lastClaims = claims.map((c) => ({
    memberId: c.id, label: c.label, why: whyOf(c), score: c.score, sticky: c.rank === 0,
  }));
  return out;
}
