/** 칭호를 붙일 최소 경기 수 — 한두 판으로 무엇의 "왕"을 부를 수는 없다. */
const MIN_PLAYS = 3;
/** 승리의 여신만 쓰는 표본 조건 — 3판 3승이 곧 "여신"이 되면 그 말이 아무것도 안 말한다.
 *  일반 판수 문턱은 걷었지만(요청: 수치로 거른다) 승률은 표본이 조건의 일부라 남는다 —
 *  종족(12판)·맵(8판)·팔색조(18판)와 같은 결이고, 설명에도 그 칭호의 조건으로 적힌다. */
const MIN_PLAYS_RATE = 8;
/** 유형 칭호(개인전·팀전 퀸)는 그 유형에서만 세는 판수라 더 많이 본다 — 팀전 몇 판으로
 *  "팀전 퀸"이 되면 정작 팀전을 도맡아 뛴 사람이 그 말을 못 듣는다. */
const MIN_PLAYS_MODE = 15;
/** 종족 칭호를 받으려면 그 종족이 제 판의 이만큼은 돼야 한다(요청: 부종족 정도는) —
 *  셋을 고루 하면 한 종족이 3분의 1이니, 4분의 1이면 "이 사람의 종족 가운데 하나"라 부를
 *  만한 선이다. 주종족(대개 절반 이상)까지 요구하지는 않는다. */
const RACE_MIN_SHARE = 0.25;
/* (삭제) MIN_PLAYS_TIER — 급별 최소 판수. 판수 문턱을 걷으면서(요청: 수치로 거른다) 함께
   없어졌다. */
/* (삭제) NAME_EDGE — 원장에서 뽑던 유닛·건물 칭호가 "무리 한가운데보다 이만큼 앞서야"를
   재던 값이다. 그 칭호들과 함께 걷었다(아래 '특징' 주석). */
/* (삭제) MIN_POOL·CROWN_EDGE·CROWN_SCORE — 상대평가(클럽 1위·왕관 물려주기) 시절의
   잣대들이다. 절대평가로 바꾸며(요청: 한 사람이 표를 싹쓸이한다) 전부 걷었다. */
/* 클럽 최다라는 것만으로는 부족하다(요청: 아무리 클럽 최다라도 판수에 비례한 최소 문턱은 다
   있게, 그래서 "칭호 없음"이 흔하게) — 서른 판을 뛰고 두 판에서 드랍을 한 사람이 그것만으로
   클럽 1등이면, 그 말은 그 사람을 부르는 말이 아니라 "다들 안 한다"는 사실의 그림자다.
   칭호는 그 사람의 색이어야 하므로, 남들보다 앞섰나(1등)와 그 사람답나(제 판의 몇 할)를
   둘 다 물어야 한다.
   급마다 다른 이유: 1급은 한 번이 곧 이야기인 드문 수(핵·리콜·성큰러시)라 같은 잣대를 대면
   통째로 잠긴다. 그래도 0은 아니다 — 스무 판에 딱 한 번은 그 사람의 색이라기엔 얇다. */
const COUNT_SHARE: Record<number, number> = { 1: 0.05, 2: 0.06 };
/** 비율과 별개의 최소 횟수(요청: 너무 겹치지 않게 문턱 높이기) — 절대평가가 되면서 조건만
 *  넘으면 다 받으니, 한 판짜리 우연까지 칭호가 되면 한 사람이 대여섯 개를 예사로 들었다.
 *  드문 수(1급)는 두 번, 흔한 수(2급)는 세 번은 나와야 버릇이라 부른다. */
const COUNT_MIN: Record<number, number> = { 1: 2, 2: 3 };
/* 한때 상한을 뒀다("아무리 많이 뛰어도 여섯 번이면 인정") — 걷어냈다(지적: 상한보다 비율
   자체를 낮추는 편이 합리적이다). 상한은 그 지점부터 비례가 끊겨, 백 판 뛴 사람과 예순 판
   뛴 사람에게 같은 수를 요구한다 — 많이 뛴 쪽이 오히려 쉬워지는 셈이다. 비율을 낮추면
   눈금이 끝까지 한 가지다.
   드문 수(1급)의 몫만 3% → 4%로 살짝 올렸다(요청: 전설·에픽의 문턱을 조금씩 높이기) —
   그쪽이 곧 왕관이 걸리는 자리라, 같은 6%를 대는 흔한 수보다 오히려 쉬웠다.
   흔한 수(2급)도 6% → 8%로 올렸다(요청: 2점대 이하도 하한 상승) — 이긴 판만 세게 된 뒤로
   같은 비율이 예전보다 헐거워졌다(분자만 줄고 분모는 그대로다).
   시뮬레이션을 보며 여러 차례 미세조정한 값이다 — 흔한 대목(격차·정찰·매너·헬프…)은 제
   문턱을 따로 가지므로(위 minPlaysShare 오버라이드), 이 기본값은 옆탱·조이기·드랍 같은
   전술이 실제로 닿을 수 있는 선이면 된다. 재분석으로 모든 비트가 세어진 뒤에도 12%에서는
   전술 칭호가 대부분 비어 있어(실측) 1급 6%·2급 8%로 내렸다 — 최소 횟수(2/3번)가 우연을
   거르는 몫을 맡는다. */
/* (삭제) LEAD_PLAYS_SHARE — "클럽 한가운데의 절반은 뛰었어야"라는 상대 잣대. 절대평가로
   바꾸며 고정 판수(MIN_PLAYS_RATE)가 그 자리를 맡는다. */

export interface EpithetSubject {
  id: string;
  stats: MemberStats;
  /* (삭제) solo / team — 유형별 전적. 칭호를 내전(팀전) 기록으로만 매기게 되면서(요청)
     위 stats가 곧 팀전이라, "개인전 퀸"은 잴 값이 없어졌고 "팀전 퀸"은 전체 승률과 같은
     수가 됐다(같은 사실을 두 이름으로 부르는 셈이다). 두 칭호와 함께 걷었다. */
  /** 종족별 전적 — 종족 칭호("저그의 절대군주")가 쓰는 값(요청: 종족 강자).
   *  통계 응답의 byRace 그대로다. 안 넘어오면 그 칭호만 안 나간다. */
  races?: Partial<Record<string, MemberStats>>;
  /** 이긴 판만 놓고 낸 같은 한 벌(통계 응답의 won) — 구성비·분당 값을 보는 칭호가 이걸
   *  쓴다(요청: 비중 칭호도 이긴 판만). 아래 mix()가 이 자리를 한 곳에서 고른다. */
  won?: MemberStats;
  /* (삭제) rise — 이번 달 레이팅 상승("떠오르는 샛별"). 레이팅은 이제 래더(일대일)에만
     있는 값이고 칭호는 내전 기록으로만 매기므로(요청), 이 화면의 어느 수와도 잣대가 맞지
     않는다. */
}

/** 칭호 한 벌 — 부르는 말과 그 근거. 근거를 함께 두는 이유는 이 줄이 "기록에서 나온 말"이라고
 *  주장하면서 정작 그 기록을 볼 길이 없으면, 읽는 사람에게는 그냥 무작위 문구와 같기 때문이다
 *  (지적: "왜 이 칭호가 나오지?"). 화면은 이 문장을 툴팁(title)으로 단다. */
export interface Epithet {
  label: string;
  why: string;
}

/* (삭제) 칭호 등급(EpithetClass·epithetClassOf) — 전설·에픽·일반으로 색을 가르던 값이다.
   색을 걷으면서(요청) 읽는 곳이 없어졌다. 등급 자체는 여전히 두 선으로 서 있다:
   sticky(승률·종족 승률·게임 수 1위)와 CROWN_SCORE(왕관 계열 이름) — 되살릴 일이 있으면
   그 둘을 그대로 읽으면 된다. */

/* 구성비·분당 값을 보는 칭호는 '이긴 판'의 원장을 본다(요청) — 무엇으로 이겼나를 묻는
   자리라, 진 판까지 섞으면 "이걸로 판을 푼다"는 말이 반쯤 거짓이 된다. 통계 화면의 도넛·
   Top5는 여전히 전체(overall)를 쓴다: 그쪽은 성과가 아니라 즐겨 쓰는 것을 보여주는 자리다.
   옛 응답에는 won이 없어 그때는 전체로 떨어진다(칭호가 통째로 사라지는 것보다 낫다). */
/** 그 사람의 '이긴 판' 살림 — 없으면 전체 살림. */
function mix(s: MemberStats, of: EpithetSubject): BuildMix | null | undefined {
  return of.won?.buildMix ?? s.buildMix;
}
/** 그 사람의 '이긴 판' 기준 수치 한 벌 — 없으면 전체. */
function won(s: MemberStats, of: EpithetSubject): MemberStats {
  return of.won ?? s;
}

/** 주요시간대 1분당 값 — 총합은 오래 뛴 사람이 늘 크다(MemberStatRow의 perMin과 같은 자). */
function perMin(total: number, seconds: number | null | undefined): number | null {
  return seconds && seconds > 0 ? (total / seconds) * PER_WINDOW_SECONDS : null;
}

/* (삭제) share() — 두 갈래의 비율(마법 유닛 비중·고급 유닛 비중·방어 건물 비중)을 재던
   자리다. 그 세 칭호가 함께 없어지면서(요청) 부르는 곳이 사라졌다. */

/** 전술 횟수 — 여러 키를 한 칭호로 묶을 때가 있다(드랍은 종족마다 키가 다르다). */
function did(s: MemberStats, ...keys: string[]): number | null {
  const t = s.tactics;
  if (!t) return null;
  const n = keys.reduce((sum, k) => sum + (t[k] ?? 0), 0);
  return n > 0 ? n : null;
}

/* (삭제) median() — 상대평가(한가운데 대비 배수)가 쓰던 도구. 절대평가와 함께 걷었다. */

/* ── 유독 잘하는 맵 ──────────────────────────────────────────────────────────── */
/** 한 맵을 '잘한다'고 부르려면 이만큼은 뛰어야 한다 — 두 판 다 이겼다고 지배자는 아니다.
 *  6 → 8판(요청: 전설·에픽의 문턱을 조금씩 높이기) — 맵 칭호는 왕관 계열이라 그 이름을
 *  달려면 그 맵에서 한동안 살아 봤어야 한다. 8 → 12판·승률 72%(요청: 맵 칭호 더 올리기) —
 *  이 클럽은 같은 맵을 오래 도는 편이라 여덟 판은 금방 쌓인다. */
const MAP_MIN_PLAYS = 12;
/** 그리고 이만큼은 이겨야 한다 — 60 → 70 → 72%(요청). 7할은 종족·전체 승률 칭호와 같은
 *  선이라, 셋이 같은 잣대를 쓴다. */
const MAP_MIN_RATE = 0.72;

/* 맵 이름 뒤에 붙는 말(요청: 맵 이름 뒤에 붙여서 재밌게) — "헌터의 여주인", "빨무의
   안주인", "투혼의 황녀"처럼 맵마다 다른 말이 붙는다. 고르는 자는 맵 이름이다: 같은 맵은
   늘 같은 말이라 조회할 때마다 바뀌지 않고, 맵이 다르면 저절로 갈린다. */
/* 꼬리말은 왕족 계열만 남긴다(요청: 점수대별로 호칭을 가르고 위쪽은 여왕·퀸·여제·황녀로)
   — "터줏대감"·"지배자"를 걷었다. 맵 칭호의 무게도 2.5 → 4다(요청: 맵 승수 높은 것은
   4점대로): 한 맵을 여섯 판 넘게 뛰고 그 대부분을 이겼다는 말이라 가벼운 자리가 아니다. */
/* 꼬리말은 '퀸' 하나다(요청: 맵도 퀸으로) — 넷을 돌려 쓰던 시절에는 같은 맵 칭호인데도
   사람마다 다른 말이 붙어(여주인·황녀…) 무엇을 뜻하는 줄인지가 한눈에 안 잡혔다. */
const MAP_SAYS = ["여왕"];

function mapPhrase(name: string): string {
  // "○○의 여왕"(요청) — 꼬리말이 하나뿐이라 맵 이름으로 고르던 자리(해시)는 그대로 없다.
  return `${name}의 ${MAP_SAYS[0]}`;
}

/** 그 사람이 가장 잘하는 맵과 그 승수. 문턱을 못 넘으면 null.
 *  값(승수)으로 겨루는 이유: 승률만 보면 딱 문턱만큼 뛴 사람이 늘 이긴다. */
function bestMap(s: MemberStats): { name: string; wins: number } | null {
  let best: { name: string; wins: number } | null = null;
  for (const [name, record] of Object.entries(s.maps ?? {})) {
    const [plays, wins] = record;
    if (plays < MAP_MIN_PLAYS || wins / plays < MAP_MIN_RATE) continue;
    if (!best || wins > best.wins) best = { name, wins };
  }
  return best;
}

/* 이름 짓는 규칙(요청) — 목록의 격(여신·퀸·일반)은 점수가 가르지만, 이름이 그 낱말로
   끝날 필요는 없다(요청: 무조건 여왕·퀸으로 끝나지 않게 — "프로토스의 수호자" 같은 것이
   "프로토스 퀸"이 되니 너무 단순해져 재미없다). 한동안 격 낱말로 통일했다가 초기의
   문장형 이름들을 도로 살렸다.
   좋은 이름의 두 갈래(요청) — 둘을 섞는다:
     · 짧고 임팩트 있는 것 — 정은퀸 · 도박 퀸 · 참여 퀸
     · 그 수의 그림이 보이는 것 — 조여오는 탱크부대 · 옆탱은 나의 힘 · 심장어택 몰래배럭 퀸
   격 낱말을 쓸 때의 결:
     여신  : 승률이 조건인 무조건 우선 칭호(승리의 여신)에만
     퀸·여왕: 판을 끌고 간 수. 앞말과 띄어 쓴다("포토러쉬 퀸") — 무엇의 퀸인지가 먼저 읽힌다
     지휘관·사령관·신·명수·왕: 운영과 손기술 — 격이 낮아지는 것이 아니라 결이 다른 말이다
   '공주'는 얼음 공주 하나뿐이다(요청) — 마엘스트롬으로 얼려 놓는 그림과 붙은 이름이라
   격이 아니라 이름으로 읽힌다.
       손대지 않는 자리도 있다(요청): 이미 수식이 붙은 이름(부티 자원퀸), 맵·종족처럼 앞에
       고유명사가 서는 줄, 그리고 말장난 하나로 완성된 이름(퀸정은) — 거기에 얹으면 수식이
       두 겹이 되거나 농담이 깨진다.
       여성형을 억지로 밀지 않는다(지적: 너무 여자를 넣다 보니 더 이상하다) — "바이오닉의
       여왕"처럼 사람이 아니라 틀·수를 가리키는 말 뒤에서는 여성형이 겉돈다. 그런 자리는
       "○○의 신"·"○○왕"이 자연스럽고, 격도 왕관과 같다.
     2점대 이하 : 그 말을 쓰지 않는다 — 장인 · 조종사 · 여인 · 머신처럼 격이 낮은 말
   예외는 두지 않는다(요청: 점수가 높으면 퀸·여왕 등으로 다시 교체) — 한때 셋방살이·역마살은
   이야기의 결이 다르다고 빼 뒀는데, 그러면 같은 5점짜리 자리에서 누구는 퀸이고 누구는
   소녀가 된다. 격을 정하는 것은 이야기의 분위기가 아니라 점수다.
   무게를 고칠 때 이름도 함께 봐야 한다: 점수는 올랐는데 이름이 그대로면 표 안에서 격이
   서로 어긋나 "왜 이건 퀸이고 저건 아닌가"가 안 읽힌다. */
/* ── 칭호 표 ──────────────────────────────────────────────────────────────────
   위에 있을수록 먼저 나간다. 차례를 이렇게 잡은 이유:

     전술 → 맵 → 스타일(무엇을 어떻게 뽑나) → 양(얼마나 했나)

   전술이 맨 위인 것은 그것이 '그 판에서 실제로 벌인 일'이라 사람을 가장 많이 말해 주기
   때문이다(요청: 자막에서 강조되는 것들). 게임 수·APM 같은 양은 누구나 시간을 들이면
   올라가는 값이라 맨 뒤에 둔다.

   전술·맵 칭호는 겨룰 사람 수(MIN_POOL)도, 한가운데와의 차이(CROWN_EDGE)도 안 따진다 —
   성큰러시를 한 사람이 클럽에 혼자뿐이라면 그게 바로 그 사람의 칭호다. 대신 min으로
   "한 번은 우연"을 걸러 낸다. */
interface Title {
  /** 화면에 적히는 말. name이 있는 줄은 {n} 자리에 그 이름이 들어간다. */
  label: string;
  /** 클수록 이 칭호에 가깝다. null이면 후보 아님. */
  /** 두 번째 인자는 그 회원의 한 벌 전체다 — 유형별 전적처럼 MemberStats 바깥에 있는 값을
   *  보는 칭호만 쓴다(개인전·팀전 퀸). 나머지는 첫 인자만 보면 된다. */
  value: (s: MemberStats, of: EpithetSubject) => number | null;
  /** 1등이라도 이 값은 넘어야 씌운다.
   *
   *  이 문턱을 value 안에서 걸면 안 된다(초기 구현의 버그): 문턱에 못 미치는 사람을 null로
   *  떨어뜨리면 후보 수가 줄어 pool을 못 넘기고, 그러면 공중 비중 89%짜리 한 명이 있어도
   *  "하늘의 여전사"가 아예 안 나간다. 겨룰 사람이 몇인가와 1등이 그럴 만한가는 서로 다른
   *  질문이라 따로 물어야 한다. */
  min?: number;
  /** 그 사람 판수의 이만큼에서는 나왔어야 한다 — 안 적으면 급에 맞는 기본값이 걸린다
   *  (COUNT_SHARE, 요청: 문턱은 다 있게).
   *
   *  0을 적으면 문턱이 없다 — 값 자체가 이미 '판당 몇'인 칭호를 위한 자리다(요청: 판당
   *  어시밀리에이터 다섯 채 같은 것은 문턱이 없어도 된다). 그런 값은 판수로 나눈 뒤의
   *  수라 여기서 다시 판수를 곱해 견주면 같은 잣대를 두 번 대는 셈이 된다.
   *
   *  전술 칭호의 값은 '그 수가 나온 판의 수'라, 스무 판 뛰고 한 판에서 캐리어를 갔다고
   *  "캐리어를 모으는 여인"이라 부르면 그 말이 그 사람을 가리키지 못한다. 드문 수(핵·리콜)는
   *  이 문턱을 안 건다 — 거기서는 한 번이 곧 이야기다. */
  minPlaysShare?: number;
  /** 후보가 이만큼은 돼야 매긴다(기본 MIN_POOL). 전술·맵은 1. */
  pool?: number;
  /** 1등이 한가운데의 몇 배는 돼야 하나(기본 CROWN_EDGE). 전술·맵은 1(안 따짐). */
  edge?: number;
  /** 값이 '이긴 판'만 센 것인가 — 전술 칭호가 그렇다(서버의 _tactic_counts가 진 판을
   *  빼고 센다, 요청). 근거 문장에 그 사실을 적으려고 들고 있는다: "옆탱 3번"과 "이긴 판에서
   *  옆탱 3번"은 다른 말이고, 뒤엣것이 이 표가 실제로 세는 값이다.
   *  마법 칭호(spell)는 원장(buildMix)에서 세므로 승패를 안 가린다 — 그래서 안 붙인다. */
  won?: boolean;
  /** 이 칭호가 타는 종족 — 판수 대비 문턱(minPlaysShare)의 분모가 전체 판수가 아니라 이
   *  종족의 판수가 된다(요청). 그 종족 기록이 안 넘어오면 전체 판수로 잰다(옛 방식). */
  race?: string;
  /** {n}에 꽂을 이름 — 맵 칭호처럼 말 자체에 그 사람의 값이 들어가는 경우. */
  name?: (s: MemberStats, of: EpithetSubject) => string | null;
  /** 툴팁에 적을 근거의 앞머리("자막에 잡힌 횟수" 등)와 단위. */
  why?: string;
  unit?: string;
  /** 칭호끼리 겨룰 때의 무게 — 없으면 표의 차례대로 나간다. */
  weight?: number;
  /** 그 값의 1등에게는 급·무게를 제치고 무조건 준다(요청: 참여수 1위는 개근의 여왕이 맞다).
   *
   *  칭호는 대개 "무엇을 했나"라 드문 쪽이 이기지만, 몇 가지는 순위 그 자체가 곧 이야기다 —
   *  클럽에서 제일 많이 나온 사람을 두고 다른 말로 부르면, 정작 그 사실을 아무도 안 부르게
   *  된다(그 사람의 1위는 다른 누구도 대신 가질 수 없는 자리다). 2등에게는 안 물려준다:
   *  1위라서 주는 칭호라 2등이 받는 순간 뜻이 사라진다. */
  sticky?: boolean;
  /** 칭호의 급(요청: 클래스가 다른 것) — 1급은 드물어서 그 자체로 표식이 되는 것들,
   *  2급은 나머지(흔한 전술·운영·수치)다.
   *
   *  급은 '무조건 먼저'가 아니라 점수에 곱하는 웃돈이다(TIER_BOOST). 한때 급을 절대 우선으로
   *  뒀더니 칭호가 사람을 설명하지 못하게 됐다(지적: 급을 넣고 나서 설명이 잘 안 맞는다) —
   *  포토러시를 딱 한 번 해 본 사람이 스무 번 드랍한 사람의 이야기를 덮어 버리는 식이었다.
   *  드묾은 값어치이지 거부권이 아니다: 웃돈으로 두면 드문 한 번이 흔한 한 번을 이기면서도,
   *  압도적인 되풀이는 여전히 제 몫을 한다. */
  tier?: number;
  /** 무게에 무엇을 곱할까.
   *
   *  "count"(전술)는 횟수 그대로다 — 포토러시 세 번은 한 번의 세 배다.
   *  "lead"(수치)는 무리 한가운데 대비 몇 배인가다(요청: 게임수·승률도 포인트다). APM 300과
   *  게임수 90은 한 자로 견줄 수가 없지만, "남들의 몇 배인가"로 바꾸면 견줄 수 있다 —
   *  압도적인 개근이 어중간한 전술 한 번보다 앞서고, 고만고만한 1등은 뒤로 간다. */
  scale?: "count" | "lead";
}

